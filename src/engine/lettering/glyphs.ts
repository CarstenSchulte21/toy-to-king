const UMLAUTS: Record<string, string> = { Ä: "A", Ö: "O", Ü: "U" };
const UMLAUT_DOTS: Glyph = [
  [
    [1, -1.4],
    [1.2, -1.4],
  ],
  [
    [2.8, -1.4],
    [3, -1.4],
  ],
];

export function glyph(ch: string, bubble = false): Glyph | null {
  const base = UMLAUTS[ch];
  if (base) return [...glyph(base, bubble)!, ...UMLAUT_DOTS];
  if (ch === "ß") return glyph("S", bubble);
  return (bubble ? BUBBLE_GLYPHS[ch] : undefined) ?? GLYPHS[ch] ?? null;
}

// Der Name, wie er an die Wand kommt: Großbuchstaben, nur Zeichen mit Skelett.
export function letteringChars(name: string): string[] {
  const chars = [...name.toUpperCase()].filter((ch) => glyph(ch) !== null);
  return chars.length > 0 ? chars : ["T", "O", "Y"];
}

// Ecken abrunden (Chaikin): für Bubble-Buchstaben.
export function chaikin(pts: Pt[], iterations: number): Pt[] {
  let out = pts;
  for (let k = 0; k < iterations; k++) {
    if (out.length < 3) return out;
    const next: Pt[] = [out[0]!];
    for (let i = 0; i < out.length - 1; i++) {
      const [ax, ay] = out[i]!;
      const [bx, by] = out[i + 1]!;
      next.push(
        [ax * 0.75 + bx * 0.25, ay * 0.75 + by * 0.25],
        [ax * 0.25 + bx * 0.75, ay * 0.25 + by * 0.75],
      );
    }
    next.push(out[out.length - 1]!);
    out = next;
  }
  return out;
}
